"""
JARVIS Security Alert Manager
Version: 8.3

Central alert management layer between:
    Security Notifications
            ↓
    Security Alert Manager
            ↓
    JARVIS / UI / Voice Layer

Responsibilities:
- Receive security notifications/events.
- Convert events into managed security alerts.
- Assign alert severity and priority.
- Deduplicate repeated alerts.
- Track active, acknowledged and resolved alerts.
- Maintain alert history.
- Notify connected JARVIS/UI callbacks.
- Provide alert statistics.
- Never perform destructive security actions directly.
"""

