_security_alert_manager: Optional[
    SecurityAlertManager
] = None

_security_alert_manager_lock = threading.Lock()


def get_security_alert_manager(
    notifications: Any = None,
    logger: Any = None,
    callback: Optional[
        Callable[[Dict[str, Any]], None]
    ] = None,
) -> SecurityAlertManager:

    global _security_alert_manager

    with _security_alert_manager_lock:

        if _security_alert_manager is None:

            _security_alert_manager = (
                SecurityAlertManager(
                    notifications=notifications,
                    logger=logger,
                    callback=callback,
                )
            )

        else:

            if notifications is not None:

                _security_alert_manager.notifications = (
                    notifications
                )

            if logger is not None:

                _security_alert_manager.logger = (
                    logger
                )

            if callback is not None:

                _security_alert_manager.set_callback(
                    callback
                )

        return _security_alert_manager