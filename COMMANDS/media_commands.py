"""
media_commands.py
Медиа-команды JARVIS.
"""

import os
import time
import subprocess
import pyautogui
import pygetwindow as gw

from COMMANDS.volume_manager import VolumeManager
from COMMANDS.media_controller import MediaController


# ==========================================================
# ВРЕМЕННЫЙ ПУТЬ К AIMP
# Потом просто замени его на настоящий путь.
# ==========================================================

AIMP_PATH = r"C:\Program Files\AIMP\AIMP.exe"


class MediaCommands:
    """
    Управление громкостью и воспроизведением медиа.
    """

    def __init__(self, logger=None):

        self.logger = logger

        self.volume = VolumeManager(logger)
        self.controller = MediaController(logger)

    # ==========================================================
    # Главный обработчик
    # ==========================================================

    def execute(self, command):

        if not command:
            return False

        command = command.lower().strip()

        self.log(
            f"Медиа-команда: {command}"
        )

        # ------------------------------------------------------
        # Включить музыку
        # ------------------------------------------------------

        if (
            "включи музыку" in command
            or "запусти музыку" in command
            or "начни музыку" in command
        ):

            return self.start_music()

        # ------------------------------------------------------
        # Следующий трек
        # ------------------------------------------------------

        if (
            "следующий трек" in command
            or "дальше" in command
        ):

            return self.controller.next_track()

        # ------------------------------------------------------
        # Предыдущий трек
        # ------------------------------------------------------

        if (
            "предыдущий трек" in command
            or "назад" in command
        ):

            return self.controller.previous_track()

        # ------------------------------------------------------
        # Громкость
        # ------------------------------------------------------

        if "громкость на" in command:

            numbers = {
                "ноль": 0,
                "десять": 10,
                "двадцать": 20,
                "тридцать": 30,
                "сорок": 40,
                "пятьдесят": 50,
                "шестьдесят": 60,
                "семьдесят": 70,
                "восемьдесят": 80,
                "девяносто": 90,
                "сто": 100
            }

            value = command.replace(
                "громкость на",
                ""
            ).strip()

            if value in numbers:

                return self.volume.set_volume(
                    numbers[value]
                )

            try:

                volume_value = int(value)

                if 0 <= volume_value <= 100:

                    return self.volume.set_volume(
                        volume_value
                    )

            except (ValueError, TypeError):

                pass

            return False

        # ------------------------------------------------------
        # Громче
        # ------------------------------------------------------

        if "громче" in command:

            return self.volume_up()

        # ------------------------------------------------------
        # Тише
        # ------------------------------------------------------

        if "тише" in command:

            return self.volume_down()

        # ------------------------------------------------------
        # Выключить звук
        # ------------------------------------------------------

        if "выключи звук" in command:

            return self.mute()

        # ------------------------------------------------------
        # Включить звук
        # ------------------------------------------------------


        if "включи звук" in command:

            return self.unmute()

        # ------------------------------------------------------
        # Пауза
        # ------------------------------------------------------

        if "пауза" in command:

            return self.pause()

        # ------------------------------------------------------
        # Продолжить
        # ------------------------------------------------------

        if (
            "продолжи" in command
            or "продолжить воспроизведение" in command
        ):

            return self.play()

        # ------------------------------------------------------
        # Неизвестная команда
        # ------------------------------------------------------

        self.log(
            f"Неизвестная медиа-команда: {command}"
        )

        return False

    # ==========================================================
    # Проверка окна AIMP
    # ==========================================================

    def find_aimp_window(self):

        try:

            windows = gw.getAllWindows()

            for window in windows:

                try:

                    title = window.title.lower().strip()

                    if "aimp" in title:

                        if window.visible:

                            return window

                except Exception:

                    continue

        except Exception as e:

            self.log(
                f"Ошибка поиска окна AIMP: {e}"
            )

        return None

    # ==========================================================
    # Запуск музыки через AIMP
    # ==========================================================

    def start_music(self):

        try:

            # --------------------------------------------------
            # Проверяем путь
            # --------------------------------------------------

            if not os.path.exists(AIMP_PATH):

                self.log(
                    f"AIMP не найден: {AIMP_PATH}"
                )

                return (
                    "AIMP не найден. "
                    "Нужно указать правильный путь."
                )

            # --------------------------------------------------
            # Проверяем, не открыт ли AIMP уже
            # --------------------------------------------------

            aimp_window = self.find_aimp_window()

            if aimp_window:

                self.log(
                    "AIMP уже открыт."
                )

            else:

                # ----------------------------------------------
                # Запускаем AIMP
                # ----------------------------------------------

                self.log(
                    "AIMP не открыт. Запускаю..."
                )

                subprocess.Popen(
                    [AIMP_PATH]
                )

            # --------------------------------------------------
            # Ждём настоящее окно AIMP
            # --------------------------------------------------

            timeout = 60
            check_interval = 0.5
            elapsed = 0

            while elapsed < timeout:

                aimp_window = self.find_aimp_window()

                if aimp_window:

                    self.log(
                        f"Окно AIMP обнаружено: "
                        f"{aimp_window.title}"
                    )

                    # ------------------------------------------
                    # Активируем окно AIMP
                    # ------------------------------------------

                    try:

                        if aimp_window.isMinimized:

                            aimp_window.restore()

                        aimp_window.activate()

                    except Exception as e:

                        self.log(
                            f"Не удалось активировать AIMP: {e}"
                        )

                    # ------------------------------------------
                    # Небольшой момент после активации
                    # ------------------------------------------

                    time.sleep(0.3)

                    # ------------------------------------------
                    # Play/Pause
                    # ------------------------------------------

                    pyautogui.press(
                        "playpause"
                    )

                    self.log(
                        "Команда Play отправлена AIMP."
                    )

                    return "Музыка включена."

                # ----------------------------------------------
                # Окна ещё нет
                # ----------------------------------------------

                time.sleep(
                    check_interval
                )

                elapsed += check_interval

            # --------------------------------------------------
            # AIMP не появился
            # --------------------------------------------------

            self.log(
                "Окно AIMP не появилось за 60 секунд."
            )

            return (
                "Не удалось дождаться "
                "загрузки AIMP."
            )

        except Exception as e:

            self.log(
                f"Ошибка запуска музыки: {e}"
            )

            return (
                "Не удалось включить музыку."
            )

    # ==========================================================
    # Громче
    # ==========================================================

    def volume_up(self):

        return self.volume.volume_up()

    # ==========================================================
    # Тише
    # ==========================================================

    def volume_down(self):

        return self.volume.volume_down()

    # ==========================================================
    # Выключить звук
    # ==========================================================

    def mute(self):

        return self.volume.mute()

    # ==========================================================
    # Включить звук
    # ==========================================================

    def unmute(self):

        return self.volume.unmute()

    # ==========================================================
    # Пауза
    # ==========================================================

    def pause(self):

        try:

            self.controller.play_pause()

            self.log(
                "Медиа поставлено на паузу"
            )

            return True

        except Exception as e:

            self.log(
                f"Ошибка паузы: {e}"
            )

            return False

    # ==========================================================
    # Продолжить воспроизведение
    # ==========================================================

    def play(self):

        try:

            self.controller.play_pause()

            self.log(
                "Воспроизведение продолжено"
            )

            return True

        except Exception as e:

            self.log(
                f"Ошибка воспроизведения: {e}"
            )

            return False

    # ==========================================================
    # Логирование
    # ==========================================================

    def log(self, message):

        if self.logger:

            self.logger.info(
                message
            )

        else:

            print(message)